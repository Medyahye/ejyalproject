import { Course, Lesson, CoursePdf } from '../types';

function makeLessons(titles: string[], baseThumb: string): Lesson[] {
  return titles.map((title, i) => ({
    id: `lesson-${baseThumb}-${i}`,
    title,
    durationMinutes: 8 + ((i * 7) % 25),
    isPreview: i === 0,
    videoUrl: 'https://example.com/mock-video.mp4',
    thumbnail: `https://picsum.photos/seed/${baseThumb}-${i}/400/250`,
  }));
}

function makePdfs(seed: string, count: number): CoursePdf[] {
  return Array.from({ length: count }).map((_, i) => ({
    id: `pdf-${seed}-${i}`,
    title: `Support de cours ${i + 1} — ${seed}`,
    sizeMb: Number((1.2 + i * 0.6).toFixed(1)),
    pages: 12 + i * 6,
    uri: 'https://example.com/mock-support.pdf',
  }));
}

